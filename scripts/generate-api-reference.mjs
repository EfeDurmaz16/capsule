import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import ts from "typescript";

function parseArgs(argv) {
  const options = {
    root: process.cwd(),
    check: false
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];

    if (arg === "--root") {
      const value = argv[index + 1];
      if (!value) {
        throw new Error("--root requires a path.");
      }
      options.root = value;
      index += 1;
    } else if (arg === "--check") {
      options.check = true;
    } else if (arg === "--help") {
      options.help = true;
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }

  return options;
}

function printUsage() {
  console.log(`Usage: node scripts/generate-api-reference.mjs [--root <path>] [--check]

Generates docs/api-reference.md from public package TypeScript entrypoints.
The generator resolves barrel exports with the TypeScript compiler API so the
committed document acts as a public API drift snapshot. With --check, nothing is
written: the command fails when the committed document differs from the
generated one, so CI reports drift instead of rewriting it.`);
}

const options = parseArgs(process.argv.slice(2));

if (options.help) {
  printUsage();
  process.exit(0);
}

const root = options.root;
const packagesDir = join(root, "packages");
const outputPath = join(root, "docs", "api-reference.md");

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function publicPackages() {
  return readdirSync(packagesDir)
    .map((dir) => join(packagesDir, dir))
    .filter((dir) => existsSync(join(dir, "package.json")))
    .map((dir) => ({ dir, pkg: readJson(join(dir, "package.json")) }))
    .filter(({ pkg }) => pkg.private !== true)
    .sort((a, b) => a.pkg.name.localeCompare(b.pkg.name));
}

const packages = publicPackages();
const sourcePaths = packages.map(({ dir }) => join(dir, "src", "index.ts")).filter((sourcePath) => existsSync(sourcePath));
const program = ts.createProgram(sourcePaths, {
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.NodeNext,
  moduleResolution: ts.ModuleResolutionKind.NodeNext,
  strict: true,
  skipLibCheck: true,
  esModuleInterop: true
});
const checker = program.getTypeChecker();

function exportedSymbols(sourcePath) {
  const sourceFile = program.getSourceFile(sourcePath);
  if (!sourceFile) {
    return [];
  }

  const moduleSymbol = checker.getSymbolAtLocation(sourceFile);
  if (!moduleSymbol) {
    return [];
  }

  return checker
    .getExportsOfModule(moduleSymbol)
    .map((symbol) => ({
      name: symbol.getName(),
      kind: exportedSymbolKind(symbol)
    }))
    .filter((symbol) => symbol.name !== "default")
    .sort((a, b) => a.name.localeCompare(b.name));
}

function exportedSymbolKind(symbol) {
  const resolved = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
  const declarations = resolved.getDeclarations() ?? symbol.getDeclarations() ?? [];
  for (const declaration of declarations) {
    if (ts.isInterfaceDeclaration(declaration)) return "interface";
    if (ts.isTypeAliasDeclaration(declaration)) return "type";
    if (ts.isClassDeclaration(declaration)) return "class";
    if (ts.isEnumDeclaration(declaration)) return "enum";
    if (ts.isFunctionDeclaration(declaration)) return "function";
    if (ts.isModuleDeclaration(declaration)) return "namespace";
    if (ts.isVariableDeclaration(declaration)) {
      const flags = ts.getCombinedNodeFlags(declaration);
      return flags & ts.NodeFlags.Const ? "const" : "variable";
    }
  }
  return "symbol";
}

const lines = [
  "# API Reference",
  "",
  "Generated by `pnpm docs:api` from public package entrypoints with TypeScript export resolution. Commit this file intentionally when the public API surface changes.",
  "",
  "This is a lightweight reference for maintainers and adapter authors. It lists package entrypoints, exported symbols, and declaration kinds; TypeScript declaration files remain the source of truth for full signatures.",
  ""
];

for (const { dir, pkg } of packages) {
  const sourcePath = join(dir, "src", "index.ts");
  const symbols = existsSync(sourcePath) ? exportedSymbols(sourcePath) : [];
  lines.push(`## ${pkg.name}`, "");
  lines.push(`- Package: \`${pkg.name}\``);
  lines.push(`- Import: \`import { ... } from "${pkg.name}"\``);
  lines.push(`- Runtime entrypoint: \`${pkg.exports?.["."]?.import ?? pkg.main ?? "./dist/index.js"}\``);
  lines.push(`- Type declarations: \`${pkg.exports?.["."]?.types ?? pkg.types ?? "./dist/index.d.ts"}\``);
  lines.push(`- Source: \`${relative(root, sourcePath)}\``);
  lines.push("");
  if (symbols.length === 0) {
    lines.push("Exports: no symbols detected from `src/index.ts`.");
  } else {
    lines.push("Exports:");
    for (const symbol of symbols) {
      lines.push(`- \`${symbol.name}\` (${symbol.kind})`);
    }
  }
  lines.push("");
}

const generated = `${lines.join("\n").trimEnd()}\n`;
if (options.check) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : undefined;
  if (current !== generated) {
    console.error(`${relative(root, outputPath)} is stale. Run pnpm docs:api and commit the result.`);
    process.exit(1);
  }
  console.log(`${relative(root, outputPath)} is current.`);
} else {
  writeFileSync(outputPath, generated);
  console.log(`Wrote ${relative(root, outputPath)}`);
}
