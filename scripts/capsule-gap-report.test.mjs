import { execFileSync, spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { domainSupportLevel, policySupportLevel, renderProviderMatrix } from "./capsule-gap-report.mjs";

describe("capsule gap report", () => {
  it("summarizes provider domains from declared capability levels", () => {
    const capabilities = {
      sandbox: {
        create: "unsupported",
        exec: "experimental"
      },
      service: {
        deploy: "native",
        rollback: "unsupported"
      },
      machine: {
        create: "unsupported"
      }
    };

    assert.equal(domainSupportLevel(capabilities, "sandbox"), "experimental");
    assert.equal(domainSupportLevel(capabilities, "service"), "native");
    assert.equal(domainSupportLevel(capabilities, "machine"), "unsupported");
    assert.equal(domainSupportLevel(capabilities, "database"), "unsupported");
  });

  it("reads policy enforcement levels from declared sandbox capabilities", () => {
    const capabilities = {
      sandbox: {
        create: "native",
        networkPolicy: "experimental",
        filesystemPolicy: "emulated"
      }
    };

    assert.equal(policySupportLevel(capabilities, "networkPolicy"), "experimental");
    assert.equal(policySupportLevel(capabilities, "filesystemPolicy"), "emulated");
    assert.equal(policySupportLevel(capabilities, "secretMounting"), "unsupported");
    assert.equal(policySupportLevel({}, "networkPolicy"), "unsupported");
  });

  it("renders real adapter rows with policy enforcement columns", () => {
    const markdown = renderProviderMatrix([
      {
        displayName: "Example",
        packageName: "@capsule-sdk/example",
        capabilities: {
          sandbox: { create: "native", exec: "native", networkPolicy: "native", filesystemPolicy: "emulated", secretMounting: "experimental" },
          job: { run: "unsupported" }
        },
        notes: "Example adapter notes."
      }
    ]);

    assert.match(markdown, /This file is generated by `pnpm capsule:gap`/);
    assert.match(markdown, /Network policy \| Filesystem policy \| Secret mounting \| Support notes/);
    assert.match(
      markdown,
      /\| Example \| `@capsule-sdk\/example` \| native \| unsupported \| unsupported \| unsupported \| unsupported \| unsupported \| unsupported \| native \| emulated \| experimental \| Example adapter notes\. \|/
    );
  });
});

describe("capsule gap report --check (CI-02)", () => {
  const repoRoot = join(import.meta.dirname, "..");
  const scriptPath = join(repoRoot, "scripts", "capsule-gap-report.mjs");

  function fixtureRoot() {
    const root = mkdtempSync(join(tmpdir(), "capsule-gap-check-"));
    for (const dir of readdirSync(join(repoRoot, "packages"))) {
      const source = join(repoRoot, "packages", dir);
      if (!existsSync(join(source, "package.json"))) continue;
      mkdirSync(join(root, "packages", dir), { recursive: true });
      cpSync(join(source, "package.json"), join(root, "packages", dir, "package.json"));
      cpSync(join(source, "src"), join(root, "packages", dir, "src"), { recursive: true });
    }
    mkdirSync(join(root, "docs"), { recursive: true });
    return root;
  }

  it("fails on a deliberately stale provider matrix without rewriting it", () => {
    const root = fixtureRoot();
    try {
      execFileSync(process.execPath, [scriptPath, "--root", root], { encoding: "utf8" });
      const matrixPath = join(root, "docs", "provider-matrix.md");
      execFileSync(process.execPath, [scriptPath, "--root", root, "--check"], { encoding: "utf8" });

      const stale = readFileSync(matrixPath, "utf8").replace("| Docker |", "| Docker (stale) |");
      writeFileSync(matrixPath, stale);
      const result = spawnSync(process.execPath, [scriptPath, "--root", root, "--check"], { encoding: "utf8" });

      assert.equal(result.status, 1);
      assert.match(result.stderr, /docs\/provider-matrix\.md is stale/);
      assert.equal(readFileSync(matrixPath, "utf8"), stale);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("the committed provider matrix matches the adapter declarations", () => {
    const result = spawnSync(process.execPath, [scriptPath, "--check"], { encoding: "utf8" });
    assert.equal(result.status, 0, result.stderr);
  });
});
