import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { domainSupportLevel, renderProviderMatrix } from "./capsule-gap-report.mjs";

describe("capsule gap report", () => {
  it("summarizes provider domains from declared capability levels", () => {
    const capabilities = {
      sandbox: {
        create: "unsupported",
        exec: "experimental"
      },
      service: {
        deploy: "native",
        rollback: "unsupported"
      },
      machine: {
        create: "unsupported"
      }
    };

    assert.equal(domainSupportLevel(capabilities, "sandbox"), "experimental");
    assert.equal(domainSupportLevel(capabilities, "service"), "native");
    assert.equal(domainSupportLevel(capabilities, "machine"), "unsupported");
    assert.equal(domainSupportLevel(capabilities, "database"), "unsupported");
  });

  it("renders real adapter rows from capability declarations", () => {
    const markdown = renderProviderMatrix([
      {
        displayName: "Example",
        packageName: "@capsule/adapter-example",
        capabilities: {
          sandbox: { create: "native", exec: "native" },
          job: { run: "unsupported" }
        },
        notes: "Example adapter notes."
      }
    ]);

    assert.match(markdown, /This file is generated by `pnpm capsule:gap`/);
    assert.match(
      markdown,
      /\| Example \| `@capsule\/adapter-example` \| native \| unsupported \| unsupported \| unsupported \| unsupported \| unsupported \| unsupported \| Example adapter notes\. \|/
    );
  });
});
