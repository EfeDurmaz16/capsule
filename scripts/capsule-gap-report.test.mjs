import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { domainSupportLevel, policySupportLevel, renderProviderMatrix } from "./capsule-gap-report.mjs";

describe("capsule gap report", () => {
  it("summarizes provider domains from declared capability levels", () => {
    const capabilities = {
      sandbox: {
        create: "unsupported",
        exec: "experimental"
      },
      service: {
        deploy: "native",
        rollback: "unsupported"
      },
      machine: {
        create: "unsupported"
      }
    };

    assert.equal(domainSupportLevel(capabilities, "sandbox"), "experimental");
    assert.equal(domainSupportLevel(capabilities, "service"), "native");
    assert.equal(domainSupportLevel(capabilities, "machine"), "unsupported");
    assert.equal(domainSupportLevel(capabilities, "database"), "unsupported");
  });

  it("reads policy enforcement levels from declared sandbox capabilities", () => {
    const capabilities = {
      sandbox: {
        create: "native",
        networkPolicy: "experimental",
        filesystemPolicy: "emulated"
      }
    };

    assert.equal(policySupportLevel(capabilities, "networkPolicy"), "experimental");
    assert.equal(policySupportLevel(capabilities, "filesystemPolicy"), "emulated");
    assert.equal(policySupportLevel(capabilities, "secretMounting"), "unsupported");
    assert.equal(policySupportLevel({}, "networkPolicy"), "unsupported");
  });

  it("renders real adapter rows with policy enforcement columns", () => {
    const markdown = renderProviderMatrix([
      {
        displayName: "Example",
        packageName: "@capsule/adapter-example",
        capabilities: {
          sandbox: { create: "native", exec: "native", networkPolicy: "native", filesystemPolicy: "emulated", secretMounting: "experimental" },
          job: { run: "unsupported" }
        },
        notes: "Example adapter notes."
      }
    ]);

    assert.match(markdown, /This file is generated by `pnpm capsule:gap`/);
    assert.match(markdown, /Network policy \| Filesystem policy \| Secret mounting \| Support notes/);
    assert.match(
      markdown,
      /\| Example \| `@capsule\/adapter-example` \| native \| unsupported \| unsupported \| unsupported \| unsupported \| unsupported \| unsupported \| native \| emulated \| experimental \| Example adapter notes\. \|/
    );
  });
});
